void OLEDDriver::initializeScreen() {
    Wire.begin(OLED_SDA_PIN, OLED_SCL_PIN);
    if (!display.begin(SSD1309_SWITCHCAPVCC, SCREEN_ADDRESS)) {
        Serial.println(F("SSD1309 allocation failed"));
        for (;;);
    }
    display.clearDisplay();
    // 40x35 icon, centered: (128-40)/2 = 44
    display.drawBitmap(44, 0, basketball_bmp, 40, 35, SSD1309_PIXEL_ON);
    display.setTextSize(2);
    display.setTextColor(SSD1309_PIXEL_ON);
    display.setCursor(18, 37);
    display.println("Welcome!");
    display.setTextSize(1);
    display.setCursor(10, 55);
    display.println("To Basketball Game");
    display.display();

}


void OLEDDriver::showCountdownIntro() {
    display.clearDisplay();
    display.setTextSize(2);
    display.setCursor(0, 20);
    display.println("Starting..");
    display.display();
    delay(3000);
    display.clearDisplay();
    
    display.setTextSize(3);
    // 3
    display.setCursor(57, 20); display.println("3"); display.display();
    delay(1000);
    display.clearDisplay();

    // 2
    display.setCursor(57, 20); display.println("2"); display.display();
    delay(1000);
    display.clearDisplay();
    
    //1
    display.setCursor(57, 20); display.println("1"); display.display();
    delay(1000);
    display.clearDisplay();
}


void OLEDDriver::showGameState(int secondsLeft, int score) {
    display.clearDisplay();

    display.setTextSize(2);
    display.setCursor(3, 8);
    display.print("Time: ");
    display.println(secondsLeft);

    display.setCursor(3, 40);
    display.print("Score: ");
    display.println(score);

    display.display();

}


void OLEDDriver::showResults(int finalScore) {
    display.clearDisplay();
    display.setTextSize(2);
    display.setCursor(34, 5);
    display.println("Final: ");
    display.setCursor(50, 30);
    display.println(finalScore);
    display.display();
    
}